"""Writes the data files the JavaScript core (web/core/) shares with the Python app, so the two
can't drift apart:

- web/core/html_entities.js: the HTML entity tables Python's html.unescape() uses.
- web/core/defaults.js: the built-in exercise list, rep ranges, bodyweight exercises and plans
  from list_of_exercise.py.

Run it again whenever list_of_exercise.py changes:

    .venv/bin/python scripts/make_js_core_data.py
"""
import html
import json
import sys
from html.entities import html5
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import list_of_exercise  # noqa: E402

CORE = ROOT / "web" / "core"
HEADER = "// Generated by scripts/make_js_core_data.py. Do not edit; change the Python source and rerun it."


def js(value) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2)


def write(name: str, lines) -> None:
    path = CORE / name
    path.write_text("\n".join([HEADER, *lines, ""]), encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size} bytes)")


write("html_entities.js", [
    f"export const HTML5 = {json.dumps(html5, ensure_ascii=True, sort_keys=True)};",
    "export const INVALID_CHARREFS = "
    f"{json.dumps({str(k): v for k, v in html._invalid_charrefs.items()}, ensure_ascii=True)};",
    f"export const INVALID_CODEPOINTS = {json.dumps(sorted(html._invalid_codepoints))};",
])

write("defaults.js", [
    f"export const LIST_OF_EXERCISES = {js(list_of_exercise.list_of_exercises)};",
    # insertion order matters: the default rep-range text lists them in this order
    f"export const DEFAULT_REP_RANGES = {js(list_of_exercise.DEFAULT_REP_RANGES)};",
    f"export const BW_EXERCISES = {js(sorted(list_of_exercise.BW_EXERCISES))};",
    f"export const DEFAULT_PLAN = {js(list_of_exercise.DEFAULT_PLAN)};",
    f"export const PREVIOUS_DEFAULT_PLANS = {js(list(list_of_exercise.PREVIOUS_DEFAULT_PLANS))};",
])
